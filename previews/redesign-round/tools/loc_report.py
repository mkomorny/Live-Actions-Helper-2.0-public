"""Measures what each component costs in each approach. Writes ../LOC-REPORT.md.

Tk figures count code lines (blank lines and comment-only lines excluded) between the
'>>> COMPONENT x' / '<<< COMPONENT x' markers in tk/tk_baseline.py and tk/tk_pushed.py.
CSS figures count lines of rules in shared/components.css whose selector starts with the
listed prefixes (the file keeps one rule per line, so a line is a rule).
"""

from __future__ import annotations

import re
from pathlib import Path

ROUND = Path(__file__).resolve().parent.parent


def tk_components(path: Path) -> dict[str, int]:
    out: dict[str, int] = {}
    cur = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"# >>> COMPONENT (\w+)", line)
        if m:
            cur, out[m.group(1)] = m.group(1), 0
            continue
        if line.startswith("# <<< COMPONENT"):
            cur = None
            continue
        if cur and line.strip() and not line.strip().startswith("#"):
            out[cur] += 1
    return out


def css_lines(path: Path, prefixes: tuple[str, ...]) -> int:
    return sum(1 for l in path.read_text(encoding="utf-8").splitlines() if l.startswith(prefixes))


base = tk_components(ROUND / "tk" / "tk_baseline.py")
push = tk_components(ROUND / "tk" / "tk_pushed.py")
comp = ROUND / "shared" / "components.css"
contract = ROUND / "shared" / "contract.css"

ROWS = [  # label, baseline key, pushed key, CSS prefixes
    ("Buttons (primary / ghost / mini)", "button", "button", (".la-btn", ".la-iconbtn")),
    ("Pills, tags, metric chips", "chip", "pill", (".la-pill", ".la-tag", ".la-chip", ".la-kind", ".la-pip")),
    ("Tool card", "tool_card", "card", (".la-card", ".la-stripe")),
    ("Track row + checkbox", None, "track_row", (".la-check", ".la-track")),
    ("Scroll container", "scroll", "scroll", ("::-webkit-scrollbar",)),
    ("Nav tabs", "nav", "nav", (".la-tab",)),
    ("Rounded plate / glow / gradient engine", None, "plate", ()),
    ("Theme loader", None, "theme_loader", ()),
]

lines = ["# Build 2 cost report (measured, not estimated)", "",
         "Code lines per component. **Tk build 1** = the app's current approach; **Tk build 2** = pushed toward the kit look;",
         "**HTML/CSS** = the same component in the shared stylesheet. Generated by `tools/loc_report.py`.", "",
         "| Component | Tk build 1 | Tk build 2 | HTML/CSS |", "|---|---:|---:|---:|"]
tb = tp = tc = 0
for label, bk, pk, pref in ROWS:
    b = base.get(bk) if bk else None
    p = push.get(pk)
    c = css_lines(comp, pref) if pref else None
    tb += b or 0
    tp += p or 0
    tc += c or 0
    lines.append(f"| {label} | {b if b is not None else 'n/a (plain Checkbutton)' if label.startswith('Track') else '-'} | {p} | {c if c is not None else '0 (border-radius / box-shadow / gradient are one declaration each)' if label.startswith('Rounded') else '0 (the contract, below)'} |")
theme_css = sum(1 for l in contract.read_text(encoding="utf-8").splitlines() if l.strip().startswith("--la-"))
lines += [f"| **Total** | **{tb}** | **{tp}** | **{tc}** |", "",
          f"The HTML side additionally has a one-time theme contract of {theme_css} lines (`shared/contract.css`) that maps any kit's tokens onto the components.", "",
          "## What the numbers do not show", "",
          "- Every Tk-build-2 component is a **picture plus hand-written behaviour**: hover, press, focus, disabled, keyboard and repaint-on-resize are code, not styling.",
          "- Widgets inside a Canvas plate are still opaque rectangles, so glows only work over a flat background colour that you must pass down by hand (`canvas_bg=`).",
          "- Build 2 reads **colours, radii and a font name** from the kit's `tokens.css`. It cannot read shadows, motion curves, `color-mix()`, rgb()/hsl() values, web fonts, or any `layout.md`.",
          "- The HTML builds read the same `tokens.css` unchanged and swap between all 11 kits with no code change (`tools/capture_matrix.js` proves identical markup).",
          "- Not attempted in build 2 because each is a further custom widget: a themed scrollbar, text inputs, select boxes, the chat surface, the console drawer, the settings forms, modals/popovers.", ""]
(ROUND / "LOC-REPORT.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
